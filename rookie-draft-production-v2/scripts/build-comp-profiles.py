#!/usr/bin/env python3
"""Build lib/comp-profiles/<class>.ts (analytics-only comp profiles) from PFF CSV exports.

usage: python3 scripts/build-comp-profiles.py <inputs.json> <csv_dir> [file_suffix]
  inputs: scripts/comp-profile-inputs/<class>.json
  csv_dir: folder with {QB,RB,WR,TE}_{primary,below_primary}.csv (PFF exports; <pos>_*secondary.csv are not needed)

These profiles feed Player Comps ONLY. They never touch grades, boards or the scouting tab.
Percent columns arrive in percent units (65.2); the site stores fractions (0.652), so they are divided by 100.
"""
import csv,json,re,sys,os

def nk(s):
    s=re.sub(r"[.'’]","",s.lower());s=re.sub(r"\b(jr|sr|ii|iii|iv)\b","",s);return re.sub(r"[^a-z]","",s)
def num(v):
    try:
        v=str(v).replace('%','').strip()
        return float(v) if v not in('','NA','nan') else None
    except: return None

# csv column -> (group, engine label, is_percent)
S,A="Season Stats","Analytical Stats"
MAP={
 'QB':[('Comp %',S,'Completion %',1),('Yards/Attempt',S,'Yards/Attempt',0),('Passing Attempts',S,'Attempts',0),('Passing TDs',S,'Touchdowns',0),('Interceptions',S,'Interceptions',0),('Rushing Attempts',S,'Rushes',0),('Games',S,'Games',0),
       ('ADOT',A,'ADOT',0),('Adjusted Comp %',A,'ADJ Comp %',1),('BTT %',A,'BTT %',1),('TWP %',A,'TWP %',1),('Scrambles',A,'Scrambles',0)],
 'RB':[('Yards/Attempt',S,'Yards/Carry',0),('Yards/Touch',S,'Yards/Touch',0),('Rush Attempts',S,'Carries',0),('Games',S,'Games',0),
       ('Elusive Rating',A,'Elusive Rating',0),('Breakaway %',A,'Breakaway %',1),('YAC/Rec',A,'YAC/Rec',0),('ADOT',A,'ADOT',0),('Pass Block Grade',A,'Pass Block Grade',0)],
 'WR':[('Yards/Rec',S,'Yards/Rec',0),('Yards/target',S,'Yards/Tgt',0),('Catch %',S,'Catch %',1),('Games',S,'Games',0),
       ('Drop %',A,'Drop %',1),('Catch in Traffic %',A,'Catch in Traffic %',1),('Y/RR',A,'Y/RR',0),('Y/RR vs Man',A,'Y/RR vs Man',0),('Y/RR vs Zone',A,'Y/RR vs Zone',0),('YAC/Rec',A,'YAC/Rec',0),('ADOT',A,'ADOT',0)],
 'TE':[('Yards/Rec',S,'Yards/Rec',0),('Yards/target',S,'Yards/Tgt',0),('Catch %',S,'Catch %',1),('Games',S,'Games',0),
       ('Drop %',A,'Drop %',1),('Y/RR',A,'Y/RR',0),('YAC/Rec',A,'YAC/Rec',0),('ADOT',A,'ADOT',0),('Inline Rate',A,'Inline Snap %',1),('Slot Rate',A,'Slot Snap %',1),('Run Block Grade',A,'Run Block Grade',0)],
}
TEAM_LIKE=lambda a,b:nk(a)[:5]==nk(b)[:5] or nk(a) in nk(b) or nk(b) in nk(a)

def main(inputs,csv_dir,suffix=''):
    cfg=json.load(open(inputs));cls=cfg['draftClass']
    rows={}
    for pos in MAP:
        for kind in ('primary','below_primary'):
            fn=os.path.join(csv_dir,f'{pos}_{kind}{suffix}.csv')
            if not os.path.exists(fn):continue
            for r in csv.DictReader(open(fn,encoding='utf-8-sig')):
                rows.setdefault((nk(r['Player']),pos),[]).append(r)
    out=[];report=[]
    for p in cfg['players']:
        hits=rows.get((nk(p['name']),p['pos']),[])
        if len(hits)>1:hits=[h for h in hits if TEAM_LIKE(h['College'],p['college'])] or hits
        if len(hits)!=1:
            report.append(f"SKIP {p['name']} ({p['pos']}): {len(hits)} matching CSV rows");continue
        r=hits[0];fields=[]
        for col,grp,label,pct in MAP[p['pos']]:
            v=num(r.get(col))
            if v is None:continue
            fields.append({'group':grp,'label':label,'value':round(v/100,6) if pct else v})
        if p.get('overall'):
            rd=p.get('round') or (1 if p['overall']<=32 else 2 if p['overall']<=64 else 3 if p['overall']<=102 else 4 if p['overall']<=138 else 5 if p['overall']<=176 else 6 if p['overall']<=216 else 7)  # pass "round" in the inputs: pick ranges per round differ by year
            draft=f"{rd}.{p['overall']}, {p['team']}"
        else:draft="UDFA"
        out.append({'name':p['name'],'position':p['pos'],'college':r['College'],'draftClass':cls,'draftResult':draft,'fields':fields})
        report.append(f"OK   {p['name']} ({p['pos']}, {r['College']}, {draft}): {len(fields)} fields")
    ts=("// GENERATED by scripts/build-comp-profiles.py from PFF exports - do not edit by hand.\n"
        "// Analytics-only comp profiles: used by Player Comps only. They never affect grades, boards or the scouting tab.\n"
        f"import type {{CompProfile}} from \"@/lib/comp-profiles/types\";\nexport const compProfiles{cls}:CompProfile[]="+json.dumps(out,ensure_ascii=False,indent=1)+";\n")
    dest=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','lib','comp-profiles',f'{cls}.ts')
    open(dest,'w').write(ts);print("\n".join(report));print(f"wrote {len(out)} profiles -> lib/comp-profiles/{cls}.ts")
if __name__=='__main__':main(sys.argv[1],sys.argv[2],sys.argv[3] if len(sys.argv)>3 else '')
